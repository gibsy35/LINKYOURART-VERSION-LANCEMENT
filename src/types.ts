export interface Contract {
  id: string;
  name: string;
  issuerId: string; // Privacy focused: ID instead of name
  totalValue: number; // Total project value in USD/EUR
  unitValue: number; // Fixed at 50
  stability: number;
  scarcity: number;
  growth: number;
  image: string;
  status: 'LIVE' | 'SUSPENDED' | 'RISK' | 'LIQUIDATION';
  description: string;
  descriptionFR?: string;
  totalUnits: number; // totalValue / 50
  availableUnits?: number; // New: Units currently available for purchase in the P2P exchange
  registryAddress: string;
  creationDate: string;
  lastAudit: string;
  registryIndex: string;
  maturityDate: string;
  pillars: PillarScore[]; // 5 pillars, 0-200 each
  totalScore: number; // 0-1000
  rights: string[];
  rarity: 'Standard' | 'Distinguished' | 'Exceptional' | 'Signature';
  category: 'Fine Art' | 'Film' | 'TV Series' | 'Music' | 'Digital Art' | 'Gaming' | 'Literature' | 'Fashion' | 'Architecture' | 'Design' | 'Photography' | 'Podcast' | 'Performing Arts' | 'Gastronomy';
  assetStatus: 'In Development' | 'Production' | 'Post-Production' | 'Completed' | 'Released' | 'Defunct';
  milestones: Milestone[];
  contractType: 'Revenue Share' | 'Direct Rights'; // Updated terminology
  revenueSharePercentage: number; // New: Percentage of future revenue
  professionalRating?: number; // New: Rating from professionals (0-1000)
  scorePro?: number; // New: Rating from professionals (0-1000)
  scoreLYA?: number; // New: Rating from LYA algorithmic analysis (0-1000)
  professionalValidator?: string; // New: Name of the professional entity that validated the project
  jurisdiction: 'France (SACD)' | 'EU (IP Law)' | 'US (Federal IP)' | 'UK (CDPA)' | 'CH (IP Law)' | 'SG (IP Law)' | 'International';
  scoreAlgo?: number; // Added for explicit SCORE ALGO
}

// Returns the project description in the requested language, falling back to the
// English text when no French translation (descriptionFR) has been written yet.
export function getContractDescription(item: { description: string; descriptionFR?: string }, language: 'EN' | 'FR'): string {
  if (language === 'FR' && item.descriptionFR) return item.descriptionFR;
  return item.description;
}

